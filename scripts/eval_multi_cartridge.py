def _get_sep_kv(
    model,
    tokenizer,
    device: str,
    sep_token: str,
) -> list[tuple[torch.Tensor, torch.Tensor]]:
    """Return per-layer (K, V) tensors for a separator token.

    Tries to capture real token KV via attention-layer hooks. Falls back to
    zero tensors if the hook can't find a (k, v) pair — still a valid boundary
    marker for testing whether any slot at the boundary reduces interference.
    """
    num_layers = model.config.num_hidden_layers
    kv_heads   = model.config.num_key_value_heads
    d_head     = model.config.hidden_size // model.config.num_attention_heads
    dtype      = next(model.parameters()).dtype

    captured: list[tuple[torch.Tensor, torch.Tensor] | None] = [None] * num_layers

    def _make_hook(idx: int):
        def hook(module, inp, out):
            # Qwen3 self_attn returns (attn_out, attn_weights, past_kv)
            # past_kv is (k, v) each (batch, kv_heads, seq, d_head)
            if isinstance(out, tuple):
                for item in out:
                    if (isinstance(item, tuple) and len(item) == 2
                            and isinstance(item[0], torch.Tensor)
                            and item[0].ndim == 4
                            and item[0].shape[-1] == d_head):
                        captured[idx] = (item[0].detach(), item[1].detach())
                        return
        return hook

    hooks = [layer.self_attn.register_forward_hook(_make_hook(i))
             for i, layer in enumerate(model.model.layers)]
    try:
        input_ids = tokenizer(sep_token, return_tensors="pt",
                              add_special_tokens=False)["input_ids"].to(device)
        with torch.inference_mode():
            model(input_ids=input_ids, use_cache=True)
    finally:
        for h in hooks:
            h.remove()

    if all(kv is not None for kv in captured):
        print(f"  [sep] Captured real '{sep_token}' KV  shape: {captured[0][0].shape}")
        return captured  # type: ignore[return-value]

    print(f"  [sep] Hook capture failed — using zero boundary tensors  "
          f"shape: (1, {kv_heads}, 1, {d_head})")
    z_k = torch.zeros(1, kv_heads, 1, d_head, device=device, dtype=dtype)
    z_v = torch.zeros(1, kv_heads, 1, d_head, device=device, dtype=dtype)
    return [(z_k.clone(), z_v.clone()) for _ in range(num_layers)]


def _make_combined_cache(
    cartridges: list[TrainableKVCartridge],
    model_config,
    sep_kv: list[tuple[torch.Tensor, torch.Tensor]] | None = None,
) -> DynamicCache:
    """Concatenate multiple cartridges along the sequence dimension into one cache.

    Each cartridge contributes its K/V tensors per layer. After concatenation the
    combined sequence length equals the sum of all individual cartridge lengths.
    Keys retain their original RoPE positions — the model must learn to disambiguate
    overlapping position embeddings across cartridges (which joint training addresses).

    If sep_kv is provided, a single-slot separator token KV is spliced between
    each pair of cartridges as a structural boundary marker.
    """
    num_layers = cartridges[0].num_layers
    combined_pkv = []
    for layer_idx in range(num_layers):
        keys, values = [], []
        for i, cart in enumerate(cartridges):
            if i > 0 and sep_kv is not None:
                keys.append(sep_kv[layer_idx][0])
                values.append(sep_kv[layer_idx][1])
            k, v = cart.layer(layer_idx)
            keys.append(k)
            values.append(v)
        combined_pkv.append((
            torch.cat(keys, dim=-2),
            torch.cat(values, dim=-2),
        ))
    return DynamicCache(ddp_cache_data=tuple(combined_pkv), config=model_config)


def _generate(
    model,
    tokenizer,
    cache_factory,      # callable → fresh DynamicCache (called once per question)
    question: str,
    device: str,
    max_new_tokens: int = 80,
) -> tuple[str, float]:
    """Generate a single answer, returning (text, elapsed_seconds)."""
    messages = [{"role": "user", "content": f"/no_think\n{question}"}]
    try:
        prompt = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True,
            enable_thinking=False,
        )
    except TypeError:
        prompt = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True,
        )
    input_ids = tokenizer(prompt, return_tensors="pt", add_special_tokens=False)["input_ids"].to(device)
    cache = cache_factory()

    t0 = time.perf_counter()
    with torch.inference_mode():
        outputs = model(
            input_ids=input_ids,
            past_key_values=cache,
            use_cache=True,
        )
        past_key_values = outputs.past_key_values
        next_token = torch.argmax(outputs.logits[:, -1, :], dim=-1, keepdim=True)

        generated_ids: list[int] = []
        eos_token_id = tokenizer.eos_token_id
        for _ in range(max_new_tokens):
            token_id = int(next_token.item())
            generated_ids.append(token_id)
            if eos_token_id is not None and token_id == eos_token_id:
                break
            outputs = model(
                input_ids=next_token,
                past_key_values=past_key_values,
                use_cache=True,
            )
            past_key_values = outputs.past_key_values
            next_token = torch.argmax(outputs.logits[:, -1, :], dim=-1, keepdim=True)
    elapsed = time.perf_counter() - t0

    text = tokenizer.decode(generated_ids, skip_special_tokens=True).strip()
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip()
    text = re.sub(r"</think>", "", text).strip()
    text = re.sub(r"^(Okay[,.].*?\n\n)", "", text, flags=re.DOTALL).strip()
    return text, elapsed


def _eval_corpus(
    *,
    corpus_name: str,
    questions: list[tuple[str, str]],
    model,
    tokenizer,
    cache_factory,
    device: str,
    max_new_tokens: int,
    domain_tag: bool = False,
) -> tuple[int, int]:
    """Run all questions for one corpus. Returns (hits, total)."""
    hits = 0
    for question, expected in questions:
        tagged = f"[{corpus_name} paper] {question}" if domain_tag else question
        answer, elapsed = _generate(
            model, tokenizer, cache_factory, tagged, device, max_new_tokens
        )
        correct = expected.lower() in answer.lower()
        hits += int(correct)
        mark = "✓" if correct else "✗"
        print(f"  {mark} Q: {question}")
        print(f"       A: {answer}")
        print(f"       [expected: {expected!r}]  {elapsed:.2f}s")
    return hits, len(questions)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Evaluate cartridges in oracle (individual) and joint (combined) modes."
    )
    parser.add_argument("--cartridge-dir", required=True,
                        help="Directory containing {name}_cartridge.pt files.")
    parser.add_argument("--names", nargs="+", default=ALL_NAMES,
                        help="Cartridge names to load, in concatenation order.")
    parser.add_argument("--mode", choices=["oracle", "joint", "both"], default="both")
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--max-new-tokens", type=int, default=80)
    parser.add_argument("--domain-tags", action="store_true",
                        help="Prefix each question with '[<name> paper]' to help the model route to the right cartridge.")
    parser.add_argument("--sep-token", type=str, default=None,
                        help="Token whose KV is spliced between cartridges as a boundary marker (e.g. '<|im_end|>').")
    parser.add_argument("--max-questions", type=int, default=None,
                        help="Use only the first N questions per corpus.")
    args = parser.parse_args()

    cartridge_dir = Path(args.cartridge_dir)

    print(f"Loading model: {DEFAULT_HF_MODEL_ID}")
    tokenizer = AutoTokenizer.from_pretrained(DEFAULT_HF_MODEL_ID)
    model = AutoModelForCausalLM.from_pretrained(
        DEFAULT_HF_MODEL_ID,
        dtype=torch.bfloat16 if args.device.startswith("cuda") else torch.float32,
        attn_implementation="sdpa",
    )
    model.to(args.device)
    model.eval()
    model_bytes = sum(p.numel() * p.element_size() for p in model.parameters())
    print(f"  Model weights: {model_bytes / 1e9:.2f} GB in GPU memory")
    if torch.cuda.is_available():
        _mem_model = torch.cuda.memory_allocated()
        print(f"  GPU allocated after model load: {_mem_model / 1e9:.2f} GB")
        _fp, _fp_param = next(iter(model.named_parameters()))
        print(f"  Model params on: {_fp_param.device}  dtype: {_fp_param.dtype}")

    # Load cartridges
    cartridges: dict[str, TrainableKVCartridge] = {}
    total_load_ms = 0.0
    for name in args.names:
        path = cartridge_dir / f"{name}_cartridge.pt"
        if not path.exists():
            raise FileNotFoundError(f"Cartridge not found: {path}")
        _mem_before = torch.cuda.memory_allocated() if torch.cuda.is_available() else 0
        _t_load = time.perf_counter()
        cart = TrainableKVCartridge.load(path, device=args.device)
        _load_ms = (time.perf_counter() - _t_load) * 1000
        total_load_ms += _load_ms
        cartridges[name] = cart
        _cart_bytes = cart.canonical_kv_bytes()
        _k0, _v0 = cart.layer(0)
        print(f"  [{name}] {cart.num_tokens} slots × {cart.num_layers} layers  "
              f"keys={tuple(_k0.shape)}  values={tuple(_v0.shape)}")
        print(f"         KV size: {_cart_bytes / 1e6:.1f} MB  "
              f"({100 * _cart_bytes / model_bytes:.2f}% of model)  loaded in {_load_ms:.0f}ms")
        if torch.cuda.is_available():
            _mem_after = torch.cuda.memory_allocated()
            _cart_param = next(iter(cart.parameters()))
            print(f"         Lives on: {_cart_param.device}  dtype: {_cart_param.dtype}  "
                  f"GPU delta: +{(_mem_after - _mem_before) / 1e6:.1f} MB  "
                  f"(total allocated: {_mem_after / 1e9:.2f} GB)")
    print(f"  Total cartridge load: {total_load_ms:.0f}ms  "
          f"(online cost at session startup)")

    # ── KV prefix injection at inference ──────────────────────────────────────
    _fc = cartridges[args.names[0]]
    _k0, _v0 = _fc.layer(0)
    print(f"\n── KV PREFIX INJECTION AT INFERENCE ──")
    print(f"  Cartridge slots injected as past_key_values: {_fc.num_tokens}")
    print(f"  Layer 0 key tensor:    shape={tuple(_k0.shape)}  (batch, kv_heads, seq, d_head)")
    print(f"  Layer 0 value tensor:  shape={tuple(_v0.shape)}")
    print(f"  No prefill at query time — document compressed offline into these {_fc.num_tokens} KV slots.")
    print(f"  Query tokens attend over this pre-loaded memory without re-reading any document text.")

    # Build per-corpus question sets (hardcoded or loaded from JSON)
    question_sets: dict[str, list[tuple[str, str]]] = {}
    for name in args.names:
        qs = _load_question_set(name, cartridge_dir)
        if qs:
            if args.max_questions:
                qs = qs[:args.max_questions]
            question_sets[name] = qs
        else:
            print(f"  [{name}] Warning: no eval questions found — skipping in eval.")
    eval_names = [n for n in args.names if n in question_sets]
    oracle_scores: dict[str, tuple[int, int]] = {}
    joint_scores:  dict[str, tuple[int, int]] = {}

    # ─── Oracle eval ─────────────────────────────────────────────────────────
    if args.mode in ("oracle", "both"):
        print("\n" + "=" * 70)
        print("ORACLE EVAL  (each cartridge loaded alone)")
        print("=" * 70)
        for name in eval_names:
            cart = cartridges[name]
            print(f"\n── {name.upper()} ({cart.num_tokens} slots) ──")
            cache_factory = lambda c=cart: c.as_cache(model.config)
            hits, total = _eval_corpus(
                corpus_name=name,
                questions=question_sets[name],
                model=model,
                tokenizer=tokenizer,
                cache_factory=cache_factory,
                device=args.device,
                max_new_tokens=args.max_new_tokens,
                domain_tag=args.domain_tags,
            )
            oracle_scores[name] = (hits, total)
            print(f"  → {hits}/{total}")

        total_oh = sum(h for h, _ in oracle_scores.values())
        total_ot = sum(t for _, t in oracle_scores.values())
        print(f"\nOracle total: {total_oh}/{total_ot}")

    # ─── Joint eval ──────────────────────────────────────────────────────────
    if args.mode in ("joint", "both"):
        all_carts = [cartridges[n] for n in args.names]
        total_slots = sum(c.num_tokens for c in all_carts)
        sep_kv = None
        if args.sep_token:
            print(f"\nComputing separator KV for token: {args.sep_token!r}")
            sep_kv = _get_sep_kv(model, tokenizer, args.device, args.sep_token)
            total_slots += len(all_carts) - 1  # one sep slot between each pair
        print("\n" + "=" * 70)
        print(f"JOINT EVAL  ({len(args.names)} cartridges concatenated, {total_slots} total slots)")
        sep_label = f" + '{args.sep_token}' separators" if args.sep_token else ""
        print(f"Order: {' | '.join(f'{n}({cartridges[n].num_tokens})' for n in args.names)}{sep_label}")
        print("=" * 70)

        joint_cache_factory = lambda: _make_combined_cache(all_carts, model.config, sep_kv=sep_kv)
        for name in eval_names:
            print(f"\n── {name.upper()} ──")
            hits, total = _eval_corpus(
                corpus_name=name,
                questions=question_sets[name],
                model=model,
                tokenizer=tokenizer,
                cache_factory=joint_cache_factory,
                device=args.device,
                max_new_tokens=args.max_new_tokens,
                domain_tag=args.domain_tags,
            )
            joint_scores[name] = (hits, total)
            print(f"  → {hits}/{total}")

        total_jh = sum(h for h, _ in joint_scores.values())
        total_jt = sum(t for _, t in joint_scores.values())
        print(f"\nJoint total: {total_jh}/{total_jt}")

    # ─── Summary table ────────────────────────────────────────────────────────
    if args.mode == "both":
        print("\n" + "=" * 70)
        print("SUMMARY")
        print("=" * 70)
        print(f"{'Corpus':<12}  {'Oracle':>8}  {'Joint':>8}  {'Drop':>6}")
        print("-" * 40)
        for name in eval_names:
            oh, ot = oracle_scores[name]
            jh, jt = joint_scores[name]
            drop = oh - jh
            print(f"{name:<12}  {oh}/{ot:>4}       {jh}/{jt:>4}    {drop:+d}")
        print("-" * 40)
        total_oh = sum(h for h, _ in oracle_scores.values())
        total_ot = sum(t for _, t in oracle_scores.values())
        total_jh = sum(h for h, _ in joint_scores.values())
        total_jt = sum(t for _, t in joint_scores.values())
        total_drop = total_oh - total_jh
        print(f"{'Total':<12}  {total_oh}/{total_ot:>4}       {total_jh}/{total_jt:>4}    {total_drop:+d}")
        print()
        if total_drop > 0:
            print(f"Interference cost: {total_drop} questions lost when loading all {len(args.names)} cartridges jointly.")
        else:
            print("No interference detected (oracle == joint).")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
