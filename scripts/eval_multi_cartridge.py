def _load_question_set(
    name: str,
    cartridge_dir: Path,
) -> list[tuple[str, str]]:
    """Return question set for a corpus name.

    Priority:
      1. Hardcoded QUESTION_SETS entry (hand-crafted, most reliable)
      2. {name}_eval_questions.json in cartridge_dir (auto-generated by train_paper_cartridges.py)
    """
    if name in QUESTION_SETS:
        return QUESTION_SETS[name]
    json_path = cartridge_dir / f"{name}_eval_questions.json"
    if json_path.exists():
        raw = json.loads(json_path.read_text(encoding="utf-8"))
        # Format: [[question, expected_substring], ...]
        return [(q, a) for q, a in raw]
    return []

